using System.Net;
using System.Text;
using PerfLens.Core.Abstractions;
using PerfLens.Core.Results;
using PerfLens.Reporting.Internal;

namespace PerfLens.Reporting;

/// <summary>
/// Writes a single self-contained <c>report.html</c>: inline CSS, inline Chart.js, an inline JSON data blob and
/// inline vanilla JS. It makes no network requests and works from file://.
/// </summary>
public sealed partial class HtmlReportWriter : IReportWriter
{
    public const string FileName = "report.html";
    /// <summary>Screenshots are inlined as data: URIs while their combined size stays under this limit.</summary>
    public const long MaxEmbeddedScreenshotBytes = 15L * 1024 * 1024;

    public string Format => "html";

    public async Task<IReadOnlyList<string>> WriteAsync(RunResult run, string outputDirectory, CancellationToken ct)
    {
        ArgumentNullException.ThrowIfNull(run);
        Directory.CreateDirectory(outputDirectory);
        var path = Path.Combine(outputDirectory, FileName);
        var html = Render(run, outputDirectory);
        await File.WriteAllTextAsync(path, html, new UTF8Encoding(false), ct);
        return [path];
    }

    /// <summary>Renders the report. <paramref name="outputDirectory"/> resolves relative screenshot paths.</summary>
    public static string Render(RunResult run, string? outputDirectory = null)
    {
        var ctx = new RenderContext(run, outputDirectory);
        var sb = new StringBuilder(512 * 1024);
        var title = string.IsNullOrWhiteSpace(run.Name) ? run.BaseUrl : run.Name;

        sb.Append("<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n")
          .Append("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n")
          .Append("<meta name=\"generator\" content=\"PerfLens ").Append(H(ctx.ToolVersion)).Append("\">\n")
          .Append("<title>PerfLens report – ").Append(H(title)).Append("</title>\n")
          .Append("<style>\n").Append(Assets.Css).Append("\n</style>\n</head>\n<body>\n");

        AppendNav(sb, ctx);
        sb.Append("<main class=\"container\">\n");
        AppendHeader(sb, ctx);
        AppendSettings(sb, ctx);
        AppendOverview(sb, ctx);
        AppendPages(sb, ctx);
        if (ctx.HasApi) AppendApi(sb, ctx);
        AppendThresholds(sb, ctx);
        AppendFindings(sb, ctx);
        if (ctx.HasRegressions) AppendBaseline(sb, ctx);
        if (ctx.HasCrawl) AppendCrawl(sb, ctx);
        AppendWarnings(sb, ctx);
        AppendGlossary(sb, ctx);
        sb.Append("</main>\n");
        AppendFooter(sb, ctx);

        sb.Append("<script type=\"application/json\" id=\"perflens-data\">").Append(BuildDataJson(ctx)).Append("</script>\n");
        sb.Append("<script>\n").Append(Assets.ChartJs).Append("\n</script>\n");
        sb.Append("<script>\n").Append(Assets.ReportJs).Append("\n</script>\n");
        sb.Append("</body>\n</html>\n");
        return sb.ToString();
    }

    private static void AppendNav(StringBuilder sb, RenderContext ctx)
    {
        var items = new List<(string Id, string Label)> { ("summary", "Summary"), ("settings", "Settings"), ("overview", "Overview"), ("pages", "Pages") };
        if (ctx.HasApi) items.Add(("api", "API"));
        items.Add(("thresholds", "Thresholds"));
        items.Add(("findings", "Findings"));
        if (ctx.HasRegressions) items.Add(("baseline", "Baseline"));
        if (ctx.HasCrawl) items.Add(("crawl", "Crawl"));
        items.Add(("warnings", "Warnings"));
        items.Add(("glossary", "Glossary"));

        sb.Append("<nav class=\"topnav\" aria-label=\"Report sections\"><div class=\"container nav-inner\">")
          .Append("<a class=\"brand\" href=\"#summary\"><span class=\"logo\">◎</span> PerfLens</a><ul>");
        foreach (var (id, label) in items)
            sb.Append("<li><a href=\"#").Append(id).Append("\">").Append(label).Append("</a></li>");
        sb.Append("</ul></div></nav>\n");
    }

    private static void AppendFooter(StringBuilder sb, RenderContext ctx)
    {
        sb.Append("<footer class=\"footer\"><div class=\"container\">Generated by <strong>PerfLens ")
          .Append(H(ctx.ToolVersion)).Append("</strong> on ").Append(H(Fmt.Date(DateTimeOffset.Now)))
          .Append(" · Run <code>").Append(H(ctx.Run.RunId)).Append("</code></div></footer>\n");
    }

    // ---------- shared helpers ----------

    /// <summary>HTML-encodes untrusted text (also safe inside double-quoted attributes).</summary>
    internal static string H(string? s) => string.IsNullOrEmpty(s) ? "" : WebUtility.HtmlEncode(s);

    internal static string HOrNa(string? s) => string.IsNullOrWhiteSpace(s) ? "<span class=\"muted\">n/a</span>" : H(s);

    /// <summary>A link for http(s) URLs only; anything else (javascript:, data:, ...) is rendered as text.</summary>
    internal static string Link(string? url, int maxLength = 0)
    {
        if (string.IsNullOrEmpty(url)) return "<span class=\"muted\">n/a</span>";
        var text = maxLength > 0 ? Truncate(url, maxLength) : url;
        var titleAttr = text.Length != url.Length ? " title=\"" + H(url) + "\"" : "";
        if (Uri.TryCreate(url, UriKind.Absolute, out var u) && (u.Scheme == Uri.UriSchemeHttp || u.Scheme == Uri.UriSchemeHttps))
            return "<a href=\"" + H(url) + "\" target=\"_blank\" rel=\"noopener noreferrer\"" + titleAttr + ">" + H(text) + "</a>";
        return "<span" + titleAttr + ">" + H(text) + "</span>";
    }

    internal static string Truncate(string s, int max)
    {
        if (s.Length <= max) return s;
        int keepEnd = Math.Max(12, max / 3);
        return s[..(max - keepEnd - 1)] + "…" + s[^keepEnd..];
    }

    internal static string GradeClass(string grade) => grade switch
    {
        "A" => "grade-a", "B" => "grade-b", "C" => "grade-c", "D" => "grade-d", "F" => "grade-f", _ => "grade-na",
    };

    internal static string SeverityClass(Severity s) => "sev-" + s.ToString().ToLowerInvariant();

    internal static void SectionStart(StringBuilder sb, string id, string title, string? subtitle = null)
    {
        sb.Append("<section id=\"").Append(id).Append("\" class=\"section\">\n<h2>").Append(title).Append("</h2>\n");
        if (subtitle != null) sb.Append("<p class=\"section-sub\">").Append(subtitle).Append("</p>\n");
    }

    internal static void SectionEnd(StringBuilder sb) => sb.Append("</section>\n");

    internal static void Empty(StringBuilder sb, string message) =>
        sb.Append("<div class=\"empty\">").Append(message).Append("</div>\n");

    internal static void ChartBox(StringBuilder sb, string canvasId, string title, string caption, int height = 320, string extraClass = "")
    {
        sb.Append("<figure class=\"chart-card ").Append(extraClass).Append("\"><figcaption><h3>").Append(title).Append("</h3><p>")
          .Append(caption).Append("</p></figcaption><div class=\"chart-box\" style=\"height:").Append(height)
          .Append("px\"><canvas id=\"").Append(canvasId).Append("\" role=\"img\" aria-label=\"").Append(H(title)).Append("\"></canvas></div></figure>\n");
    }

    /// <summary>Per-render state: the run plus pre-computed, null-safe views.</summary>
    internal sealed class RenderContext
    {
        public RenderContext(RunResult run, string? outputDirectory)
        {
            Run = run;
            OutputDirectory = outputDirectory;
            Statistic = ReportFacts.Statistic(run);
            ToolVersion = string.IsNullOrWhiteSpace(run.Environment.ToolVersion) ? ToolInfo.Version : run.Environment.ToolVersion;
            Pages = run.Pages.Select((p, i) => new PageView(i, p, ReportFacts.Metrics(p))).ToList();
            Screenshots = ScreenshotResolver.Resolve(run.Pages, outputDirectory);
        }

        public RunResult Run { get; }
        public AnalysisResult? Analysis => Run.Analysis;
        public string? OutputDirectory { get; }
        public string Statistic { get; }
        public string ToolVersion { get; }
        public List<PageView> Pages { get; }
        public IReadOnlyDictionary<PageResult, string> Screenshots { get; }
        public bool HasApi => Run.Api?.Endpoints.Count > 0;
        public bool HasRegressions => Run.Analysis?.Regressions.Count > 0;
        public bool HasCrawl => Run.Crawl != null;
        public string StatLabel => Statistic switch { "median" or "p50" => "median (p50)", "avg" => "mean", _ => Statistic };
    }

    internal sealed record PageView(int Index, PageResult Page, Dictionary<string, MetricStats> Metrics)
    {
        public string Id => "page-" + Index;
        public double? Score => ReportFacts.Score(Page);
        public string Grade => ReportFacts.Grade(Score);
        public double? Value(string metric, string statistic) => ReportFacts.Value(Metrics, metric, statistic);
    }
}
