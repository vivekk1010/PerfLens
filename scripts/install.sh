#!/usr/bin/env bash
# PerfLens installer for Linux, WSL and macOS.
# Ensures the .NET 10 SDK, publishes the CLI, creates a `perflens` wrapper and installs Playwright browsers.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
CLI_PROJECT="$REPO_ROOT/src/PerfLens.Cli/PerfLens.Cli.csproj"
DOTNET_INSTALL_URL="https://dot.net/v1/dotnet-install.sh"
DOTNET_CHANNEL="10.0"
USER_DOTNET_DIR="$HOME/.dotnet"
PROFILE_BEGIN="# >>> perflens >>>"
PROFILE_END="# <<< perflens <<<"
WRAPPER_MARKER="# Generated by PerfLens scripts/install.sh"

PREFIX="${PERFLENS_PREFIX:-$HOME/.local}"
BROWSERS="chromium"
WITH_DEPS=0
SKIP_BROWSERS=0
SKIP_BUILD=0
UPDATE_PROFILE=0
UNINSTALL=0
DRY_RUN=0

OS=""
ARCH=""
IS_WSL=0
DISTRO_ID=""
DISTRO_VERSION=""
DOTNET_BIN=""
PLAYWRIGHT_OVERRIDE=""
PROFILE_LINES=()
SUDO_WARNED=0

if [[ -t 1 && -z "${NO_COLOR:-}" ]]; then
  C_RESET=$'\033[0m' C_BOLD=$'\033[1m' C_BLUE=$'\033[34m' C_GREEN=$'\033[32m' C_YELLOW=$'\033[33m' C_RED=$'\033[31m'
else
  C_RESET="" C_BOLD="" C_BLUE="" C_GREEN="" C_YELLOW="" C_RED=""
fi

step() { printf '\n%s==>%s %s%s%s\n' "$C_BLUE" "$C_RESET" "$C_BOLD" "$*" "$C_RESET"; }
info() { printf '    %s\n' "$*"; }
ok()   { printf '    %s✔%s %s\n' "$C_GREEN" "$C_RESET" "$*"; }
warn() { printf '    %s!%s %s\n' "$C_YELLOW" "$C_RESET" "$*" >&2; }
die()  { printf '%serror:%s %s\n' "$C_RED" "$C_RESET" "$*" >&2; exit 1; }

usage() {
  cat <<EOF
Usage: scripts/install.sh [options]

Installs PerfLens: .NET 10 SDK (if missing), the published CLI, a 'perflens'
wrapper on your PATH and Playwright browsers.

Options:
  --prefix DIR          Install prefix (default: \$HOME/.local)
                        CLI goes to DIR/lib/perflens, wrapper to DIR/bin/perflens
  --browsers LIST       Browsers to install: chromium|firefox|webkit|all or a
                        comma-separated list (default: chromium)
  --with-deps           Also install OS libraries for the browsers (uses sudo)
  --skip-browsers       Do not install Playwright browsers
  --skip-build          Do not publish the CLI (reuse an existing install)
  --update-profile      Append PATH / DOTNET_ROOT settings to your shell profile
  --uninstall           Remove the wrapper, published CLI and profile block
  --dry-run             Print the actions without changing anything
  -h, --help            Show this help

Environment:
  PERFLENS_PREFIX       Default for --prefix
  NO_COLOR              Disable coloured output

Notes:
  * On Ubuntu 20.04 Playwright no longer ships native browser builds; the
    wrapper exports PLAYWRIGHT_HOST_PLATFORM_OVERRIDE=ubuntu22.04-x64 so the
    Ubuntu 22.04 builds are used instead.
  * Re-running the script is safe; it updates the existing installation.
EOF
}

# Runs a command, or prints it in --dry-run mode.
run() {
  if (( DRY_RUN )); then
    printf '    %s[dry-run]%s' "$C_YELLOW" "$C_RESET"
    printf ' %q' "$@"
    printf '\n'
  else
    "$@"
  fi
}

have() { command -v "$1" >/dev/null 2>&1; }

parse_args() {
  while (( $# > 0 )); do
    case "$1" in
      --prefix) [[ $# -ge 2 ]] || die "--prefix needs a value"; PREFIX="$2"; shift ;;
      --prefix=*) PREFIX="${1#*=}" ;;
      --browsers) [[ $# -ge 2 ]] || die "--browsers needs a value"; BROWSERS="$2"; shift ;;
      --browsers=*) BROWSERS="${1#*=}" ;;
      --with-deps) WITH_DEPS=1 ;;
      --skip-browsers) SKIP_BROWSERS=1 ;;
      --skip-build) SKIP_BUILD=1 ;;
      --update-profile) UPDATE_PROFILE=1 ;;
      --uninstall) UNINSTALL=1 ;;
      --dry-run) DRY_RUN=1 ;;
      -h|--help) usage; exit 0 ;;
      *) die "unknown option '$1' (see --help)" ;;
    esac
    shift
  done
  [[ -n "$PREFIX" ]] || die "--prefix must not be empty"
  PREFIX="${PREFIX%/}"
  [[ "$PREFIX" = /* ]] || PREFIX="$PWD/$PREFIX"

  local b
  IFS=',' read -r -a BROWSER_LIST <<< "$BROWSERS"
  for b in "${BROWSER_LIST[@]}"; do
    case "$b" in
      chromium|firefox|webkit|all) ;;
      *) die "unsupported browser '$b' (use chromium, firefox, webkit or all)" ;;
    esac
  done
}

detect_platform() {
  step "Checking platform"
  case "$(uname -s)" in
    Linux) OS=linux ;;
    Darwin) OS=macos ;;
    *) die "unsupported OS '$(uname -s)'. PerfLens supports Linux, WSL and macOS (use PowerShell/winget on Windows)." ;;
  esac
  case "$(uname -m)" in
    x86_64|amd64) ARCH=x64 ;;
    aarch64|arm64) ARCH=arm64 ;;
    *) die "unsupported CPU architecture '$(uname -m)'" ;;
  esac
  if [[ "$OS" == linux ]] && grep -qi microsoft /proc/version 2>/dev/null; then IS_WSL=1; fi
  if [[ -r /etc/os-release ]]; then
    DISTRO_ID="$(. /etc/os-release && printf '%s' "${ID:-}")"
    DISTRO_VERSION="$(. /etc/os-release && printf '%s' "${VERSION_ID:-}")"
  fi
  local desc="$OS/$ARCH"
  [[ -n "$DISTRO_ID" ]] && desc+=" ($DISTRO_ID $DISTRO_VERSION)"
  (( IS_WSL )) && desc+=" on WSL"
  ok "$desc"

  if [[ "$DISTRO_ID" == ubuntu && "$DISTRO_VERSION" == 20.04 ]]; then
    PLAYWRIGHT_OVERRIDE="ubuntu22.04-$ARCH"
    warn "Ubuntu 20.04 is not supported by current Playwright builds; using PLAYWRIGHT_HOST_PLATFORM_OVERRIDE=$PLAYWRIGHT_OVERRIDE"
  fi
  if [[ -n "${PLAYWRIGHT_HOST_PLATFORM_OVERRIDE:-}" ]]; then
    PLAYWRIGHT_OVERRIDE="$PLAYWRIGHT_HOST_PLATFORM_OVERRIDE"
  fi
  [[ -n "$PLAYWRIGHT_OVERRIDE" ]] && export PLAYWRIGHT_HOST_PLATFORM_OVERRIDE="$PLAYWRIGHT_OVERRIDE"

  if have git; then ok "git $(git --version | awk '{print $3}')"; else warn "git not found (only needed to clone/update the repository)"; fi
  if have curl; then ok "curl found"; elif have wget; then ok "wget found"; else warn "neither curl nor wget found (needed to download .NET)"; fi
}

has_sdk10() { "$1" --list-sdks 2>/dev/null | grep -qE '^10\.'; }

ensure_dotnet() {
  step "Checking .NET 10 SDK"
  local candidate
  for candidate in "$(command -v dotnet 2>/dev/null || true)" "$USER_DOTNET_DIR/dotnet"; do
    if [[ -n "$candidate" && -x "$candidate" ]] && has_sdk10 "$candidate"; then
      DOTNET_BIN="$(readlink -f "$candidate" 2>/dev/null || printf '%s' "$candidate")"
      ok ".NET SDK $("$candidate" --list-sdks | grep -E '^10\.' | tail -1 | awk '{print $1}') at $(dirname "$DOTNET_BIN")"
      break
    fi
  done

  if [[ -z "$DOTNET_BIN" ]]; then
    info ".NET 10 SDK not found; installing to $USER_DOTNET_DIR (channel $DOTNET_CHANNEL)"
    local tmp
    tmp="$(mktemp -d)"
    # shellcheck disable=SC2064
    trap "rm -rf '$tmp'" EXIT
    if have curl; then
      run curl -fsSL "$DOTNET_INSTALL_URL" -o "$tmp/dotnet-install.sh"
    elif have wget; then
      run wget -q "$DOTNET_INSTALL_URL" -O "$tmp/dotnet-install.sh"
    else
      die "curl or wget is required to download the .NET SDK"
    fi
    run bash "$tmp/dotnet-install.sh" --channel "$DOTNET_CHANNEL" --install-dir "$USER_DOTNET_DIR"
    DOTNET_BIN="$USER_DOTNET_DIR/dotnet"
    if (( ! DRY_RUN )); then
      has_sdk10 "$DOTNET_BIN" || die ".NET SDK installation failed"
      ok "installed .NET SDK to $USER_DOTNET_DIR"
    fi
  fi

  local dotnet_dir
  dotnet_dir="$(dirname "$DOTNET_BIN")"
  export DOTNET_ROOT="$dotnet_dir"
  case ":$PATH:" in *":$dotnet_dir:"*) ;; *) export PATH="$dotnet_dir:$PATH" ;; esac
  if [[ "$dotnet_dir" == "$USER_DOTNET_DIR" ]]; then
    PROFILE_LINES+=("export DOTNET_ROOT=\"$USER_DOTNET_DIR\"" "export PATH=\"$USER_DOTNET_DIR:\$PATH\"")
  fi
  export DOTNET_CLI_TELEMETRY_OPTOUT="${DOTNET_CLI_TELEMETRY_OPTOUT:-1}"
  export DOTNET_NOLOGO=1
}

publish_cli() {
  local lib_dir="$PREFIX/lib/perflens"
  if (( SKIP_BUILD )); then
    step "Skipping build (--skip-build)"
    [[ -f "$lib_dir/perflens.dll" ]] || (( DRY_RUN )) || die "no existing install at $lib_dir; run without --skip-build"
    return
  fi
  step "Publishing PerfLens to $lib_dir"
  [[ -f "$CLI_PROJECT" ]] || die "CLI project not found at $CLI_PROJECT (run this script from a PerfLens checkout)"
  run rm -rf "$lib_dir"
  run mkdir -p "$lib_dir"
  run "$DOTNET_BIN" publish "$CLI_PROJECT" -c Release -o "$lib_dir" --nologo -v quiet
  if (( ! DRY_RUN )); then
    [[ -f "$lib_dir/perflens.dll" ]] || die "publish did not produce $lib_dir/perflens.dll"
    ok "published"
  fi
}

write_wrapper() {
  local bin_dir="$PREFIX/bin" lib_dir="$PREFIX/lib/perflens" wrapper="$PREFIX/bin/perflens"
  step "Creating wrapper $wrapper"
  if [[ -e "$wrapper" ]] && ! grep -qF "$WRAPPER_MARKER" "$wrapper" 2>/dev/null; then
    die "$wrapper exists and was not created by this installer; remove it or use --prefix"
  fi
  local content override_line=""
  if [[ -n "$PLAYWRIGHT_OVERRIDE" ]]; then
    override_line="export PLAYWRIGHT_HOST_PLATFORM_OVERRIDE=\"\${PLAYWRIGHT_HOST_PLATFORM_OVERRIDE:-$PLAYWRIGHT_OVERRIDE}\""
  fi
  content="$(cat <<EOF
#!/usr/bin/env bash
$WRAPPER_MARKER
set -euo pipefail
LIB_DIR="$lib_dir"
DOTNET_BIN="$DOTNET_BIN"
export DOTNET_ROOT="\${DOTNET_ROOT:-$(dirname "$DOTNET_BIN")}"
$override_line
if [[ -x "\$DOTNET_BIN" ]]; then
  exec "\$DOTNET_BIN" "\$LIB_DIR/perflens.dll" "\$@"
elif [[ -x "\$LIB_DIR/perflens" ]]; then
  exec "\$LIB_DIR/perflens" "\$@"
fi
exec dotnet "\$LIB_DIR/perflens.dll" "\$@"
EOF
)"
  if (( DRY_RUN )); then
    info "[dry-run] would write $wrapper:"
    printf '%s\n' "$content" | sed 's/^/      | /'
  else
    mkdir -p "$bin_dir"
    printf '%s\n' "$content" > "$wrapper"
    chmod +x "$wrapper"
    ok "wrapper written"
  fi
  case ":$PATH:" in
    *":$bin_dir:"*) ok "$bin_dir is on PATH" ;;
    *) PROFILE_LINES+=("export PATH=\"$bin_dir:\$PATH\""); warn "$bin_dir is not on PATH" ;;
  esac
  export PATH="$bin_dir:$PATH"
}

profile_file() {
  case "$(basename "${SHELL:-bash}")" in
    zsh) printf '%s' "$HOME/.zshrc" ;;
    *) printf '%s' "$HOME/.bashrc" ;;
  esac
}

remove_profile_block() {
  local file="$1"
  if [[ ! -f "$file" ]] || ! grep -qF "$PROFILE_BEGIN" "$file"; then return 0; fi
  if (( DRY_RUN )); then info "[dry-run] would remove the PerfLens block from $file"; return 0; fi
  local tmp
  tmp="$(mktemp)"
  awk -v b="$PROFILE_BEGIN" -v e="$PROFILE_END" '$0==b{skip=1;next} $0==e{skip=0;next} !skip' "$file" > "$tmp"
  cat "$tmp" > "$file"
  rm -f "$tmp"
  ok "removed PerfLens block from $file"
}

update_profile() {
  [[ -n "$PLAYWRIGHT_OVERRIDE" ]] && PROFILE_LINES+=("export PLAYWRIGHT_HOST_PLATFORM_OVERRIDE=\"$PLAYWRIGHT_OVERRIDE\"")
  (( ${#PROFILE_LINES[@]} > 0 )) || return 0
  local file
  file="$(profile_file)"
  step "Shell profile"
  if (( UPDATE_PROFILE )); then
    remove_profile_block "$file"
    if (( DRY_RUN )); then
      info "[dry-run] would append to $file:"
      printf '      | %s\n' "$PROFILE_BEGIN" "${PROFILE_LINES[@]}" "$PROFILE_END"
    else
      printf '\n%s\n' "$PROFILE_BEGIN" >> "$file"
      printf '%s\n' "${PROFILE_LINES[@]}" "$PROFILE_END" >> "$file"
      ok "updated $file (open a new shell or run: source $file)"
    fi
  else
    info "Add these lines to $file (or re-run with --update-profile):"
    printf '      %s\n' "${PROFILE_LINES[@]}"
  fi
}

sudo_cmd() {
  if [[ "$(id -u)" -eq 0 ]]; then
    run "$@"
  elif have sudo; then
    if (( ! SUDO_WARNED )) && ! sudo -n true 2>/dev/null; then
      warn "sudo will ask for your password"
      SUDO_WARNED=1
    fi
    run sudo "$@"
  else
    die "installing OS dependencies needs root or sudo"
  fi
}

# Prints how OS dependencies get installed: none (macOS), apt (manual list) or playwright (install-deps).
deps_strategy() {
  if [[ "$OS" == macos ]]; then printf 'none'
  elif [[ "$DISTRO_ID" == ubuntu && "$DISTRO_VERSION" == 20.04 ]]; then printf 'apt'
  else printf 'playwright'
  fi
}

install_apt_deps() {
  step "Installing OS dependencies for browsers"
  # Playwright's install-deps does not support Ubuntu 20.04; install the common Chromium libraries directly.
  info "Ubuntu 20.04: installing common Chromium libraries with apt-get"
  sudo_cmd apt-get update
  sudo_cmd apt-get install -y --no-install-recommends \
    libnss3 libatk1.0-0 libatk-bridge2.0-0 libcups2 libdrm2 libxkbcommon0 libxcomposite1 \
    libxdamage1 libxfixes3 libxrandr2 libgbm1 libasound2 libpango-1.0-0 libcairo2
  (( DRY_RUN )) || ok "OS dependencies installed"
}

install_browsers() {
  if (( SKIP_BROWSERS )); then step "Skipping browsers (--skip-browsers)"; return; fi
  local perflens="$PREFIX/bin/perflens" deps_flag="" b strategy
  if (( WITH_DEPS )); then
    strategy="$(deps_strategy)"
    case "$strategy" in
      none) info "OS dependencies are not needed on macOS" ;;
      apt) install_apt_deps ;;
      playwright) deps_flag="--with-deps"; warn "Playwright will install OS dependencies with sudo" ;;
    esac
  fi
  for b in "${BROWSER_LIST[@]}"; do
    step "Installing Playwright browser: $b"
    if [[ -n "$deps_flag" ]]; then
      run "$perflens" install-browsers "$b" "$deps_flag"
    else
      run "$perflens" install-browsers "$b"
    fi
  done
  (( DRY_RUN )) || ok "browsers installed"
}

verify() {
  step "Verifying installation"
  local perflens="$PREFIX/bin/perflens"
  if (( DRY_RUN )); then
    run "$perflens" --version
    run "$perflens" doctor
    return
  fi
  local version
  version="$("$perflens" --version 2>&1)" || die "'perflens --version' failed: $version"
  ok "$version"
  if "$perflens" --help 2>/dev/null | grep -qw doctor; then
    if (( SKIP_BROWSERS )); then
      info "skipping 'perflens doctor' (browsers were not installed)"
    elif "$perflens" doctor; then
      ok "perflens doctor passed"
    else
      warn "'perflens doctor' reported problems (see above); try --with-deps"
    fi
  else
    info "'perflens doctor' is not available in this build; skipped"
  fi
}

uninstall() {
  step "Uninstalling PerfLens from $PREFIX"
  local wrapper="$PREFIX/bin/perflens" lib_dir="$PREFIX/lib/perflens"
  if [[ -f "$wrapper" ]]; then
    if grep -qF "$WRAPPER_MARKER" "$wrapper"; then run rm -f "$wrapper"; ok "removed $wrapper"
    else warn "$wrapper was not created by this installer; left in place"; fi
  else
    info "no wrapper at $wrapper"
  fi
  if [[ -d "$lib_dir" ]]; then run rm -rf "$lib_dir"; ok "removed $lib_dir"; else info "no install at $lib_dir"; fi
  remove_profile_block "$HOME/.bashrc"
  remove_profile_block "$HOME/.zshrc"
  info "Playwright browsers in ~/.cache/ms-playwright (or ~/Library/Caches/ms-playwright) are shared with other tools and were kept."
  info "The .NET SDK was kept."
}

next_steps() {
  step "Done"
  cat <<EOF
    Next steps:
      perflens --help
      perflens init perflens.yaml                     # starter config
      perflens run -c configs/demoshop-quick.json     # needs DemoShop running
      scripts/run-demo.sh                              # builds + runs DemoShop and benchmarks it
EOF
  if [[ -n "$PLAYWRIGHT_OVERRIDE" ]]; then
    info "Note: PLAYWRIGHT_HOST_PLATFORM_OVERRIDE=$PLAYWRIGHT_OVERRIDE is set by the wrapper for this platform."
  fi
}

main() {
  parse_args "$@"
  (( DRY_RUN )) && printf '%sDry run: no changes will be made.%s\n' "$C_YELLOW" "$C_RESET"
  if (( UNINSTALL )); then uninstall; return; fi
  detect_platform
  ensure_dotnet
  publish_cli
  write_wrapper
  install_browsers
  update_profile
  verify
  next_steps
}

main "$@"
